// Get all catalogue products (only active ones)
export function getCatalogueProducts(): Product[] {
  return activeProducts.filter((p) => p.active);
}

// Get featured products
export function getFeaturedProducts(): Product[] {
  return activeProducts.filter((p) => p.active && p.featured);
}

// Get products by category
export function getProductsByCategory(category: 'chicken' | 'mutton' | 'eggs'): Product[] {
  return activeProducts.filter((p) => p.active && p.category === category);
}

// Get products by subcategory
export function getProductsBySubcategory(
  category: 'chicken' | 'mutton',
  subcategory: string
): Product[] {
  return activeProducts.filter(
    (p) => p.active && p.category === category && p.subcategory === subcategory
  );
}
